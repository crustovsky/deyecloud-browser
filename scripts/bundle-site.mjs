#!/usr/bin/env node
// Embeds the Astro build (dist/) into the Worker as a generated module.
//
// Why not Workers static assets: Workers with assets run behind an internal router
// that does not pass ctx.access to the Worker, so the "private unless Access
// authenticated" check would always fail. The site is about 100 KB, so it simply
// ships inside the Worker bundle instead.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";

const DIST = "dist";
const OUT = "worker/site.generated.ts";
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json; charset=utf-8",
  ".txt": "text/plain; charset=utf-8",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
};
const TEXT = new Set([".html", ".js", ".css", ".svg", ".json", ".txt"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = {};
for (const file of walk(DIST)) {
  const ext = extname(file);
  const type = TYPES[ext];
  if (!type) throw new Error(`no content type for ${file}`);
  const path = "/" + relative(DIST, file).split("\\").join("/");
  const buf = readFileSync(file);
  files[path] = TEXT.has(ext) ? { type, text: buf.toString("utf8") } : { type, base64: buf.toString("base64") };
}

const out =
  "// Generated by scripts/bundle-site.mjs from dist/. Do not edit.\n" +
  "export interface SiteFile { type: string; text?: string; base64?: string }\n" +
  `export const SITE: Record<string, SiteFile> = ${JSON.stringify(files)};\n`;
writeFileSync(OUT, out);
console.log(`bundled ${Object.keys(files).length} files (${(out.length / 1024).toFixed(0)} KB) into ${OUT}`);
